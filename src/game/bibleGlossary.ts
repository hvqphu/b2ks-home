export function lookupBibleWordMeaning(rawToken: string): { word: string; meaningVi: string } | null {
  const cleaned = String(rawToken || '')
    .replace(/^[^a-zA-Z]+|[^a-zA-Z']+$/g, '')
    .replace(/'s$/i, '')
    .replace(/s'$/i, 's')
    .toLowerCase()
    .trim();
  if (!cleaned) return null;

  const direct = BIBLE_WORD_DICTIONARY[cleaned];
  if (direct) return { word: cleaned, meaningVi: direct };

  // Try common English inflectional stems
  const candidates: string[] = [];
  if (cleaned.endsWith('ies') && cleaned.length > 4) candidates.push(cleaned.slice(0, -3) + 'y');
  if (cleaned.endsWith('es') && cleaned.length > 3) candidates.push(cleaned.slice(0, -2));
  if (cleaned.endsWith('s') && cleaned.length > 2) candidates.push(cleaned.slice(0, -1));
  if (cleaned.endsWith('ied') && cleaned.length > 4) candidates.push(cleaned.slice(0, -3) + 'y');
  if (cleaned.endsWith('ed') && cleaned.length > 3) {
    candidates.push(cleaned.slice(0, -2));
    candidates.push(cleaned.slice(0, -1));
  }
  if (cleaned.endsWith('ing') && cleaned.length > 4) {
    candidates.push(cleaned.slice(0, -3));
    candidates.push(cleaned.slice(0, -3) + 'e');
  }

  for (const cand of candidates) {
    if (BIBLE_WORD_DICTIONARY[cand]) {
      return { word: cleaned, meaningVi: BIBLE_WORD_DICTIONARY[cand] };
    }
  }
  return null;
}
